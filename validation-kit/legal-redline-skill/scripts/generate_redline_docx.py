def generate_redline(input_json_path, output_docx_path):
    with open(input_json_path, "r", encoding="utf-8") as fh:
        data = json.load(fh)

    lang = data.get("language", "en")
    L = LANG_STRINGS.get(lang, LANG_STRINGS["en"])

    doc = Document()

    # Wider margins so margin comments have room
    for section in doc.sections:
        section.left_margin = Inches(0.8)
        section.right_margin = Inches(2.4)
        section.top_margin = Inches(0.8)
        section.bottom_margin = Inches(0.8)

    build_cover(doc, data, L)

    for i, change in enumerate(data.get("changes", [])):
        build_change_block(doc, change, L, i)

    build_overview_table(doc, data, L)
    add_footer(doc, L)

    doc.save(output_docx_path)
    print(f"✓ Generated: {output_docx_path}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print("Usage: python3 generate_redline_docx.py <input.json> <output.docx>")
        sys.exit(1)
    generate_redline(sys.argv[1], sys.argv[2])
