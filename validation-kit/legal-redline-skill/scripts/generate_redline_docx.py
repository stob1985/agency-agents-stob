_revision_counter = {"id": 1000}


def _next_rev_id():
    _revision_counter["id"] += 1
    return _revision_counter["id"]


def _run_with_props(text, *, strike=False, color=None, underline=False, bold=False, italic=False):
    """Build a w:r element with text + visual fallback formatting."""
    r = OxmlElement("w:r")
    rpr = OxmlElement("w:rPr")
    if bold:
        rpr.append(OxmlElement("w:b"))
    if italic:
        rpr.append(OxmlElement("w:i"))
    if strike:
        rpr.append(OxmlElement("w:strike"))
    if underline:
        u = OxmlElement("w:u")
        u.set(qn("w:val"), "single")
        rpr.append(u)
    if color:
        c = OxmlElement("w:color")
        c.set(qn("w:val"), color)
        rpr.append(c)
    r.append(rpr)
    t = OxmlElement("w:t")
    t.text = text
    t.set(qn("xml:space"), "preserve")
    r.append(t)
    return r


def add_tracked_deletion(paragraph, text):
    """Add a deletion as a real w:del + visual red strikethrough fallback."""
    p_el = paragraph._p
    del_el = OxmlElement("w:del")
    del_el.set(qn("w:id"), str(_next_rev_id()))
    del_el.set(qn("w:author"), AUTHOR)
    del_el.set(qn("w:date"), DATE)

    r = OxmlElement("w:r")
    rpr = OxmlElement("w:rPr")
    strike = OxmlElement("w:strike")
    rpr.append(strike)
    color = OxmlElement("w:color")
    color.set(qn("w:val"), "C0392B")
    rpr.append(color)
    r.append(rpr)
    # For deletions Word uses w:delText
    dt = OxmlElement("w:delText")
    dt.text = text
    dt.set(qn("xml:space"), "preserve")
    r.append(dt)
    del_el.append(r)
    p_el.append(del_el)


def add_tracked_insertion(paragraph, text):
    """Add an insertion as a real w:ins + visual green underline fallback."""
    p_el = paragraph._p
    ins_el = OxmlElement("w:ins")
    ins_el.set(qn("w:id"), str(_next_rev_id()))
    ins_el.set(qn("w:author"), AUTHOR)
    ins_el.set(qn("w:date"), DATE)

    r = _run_with_props(text, underline=True, color="2E8636")
    ins_el.append(r)
    p_el.append(ins_el)


