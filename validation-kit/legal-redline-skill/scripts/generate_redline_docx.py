def _make_element(tag, **attrs):
    el = OxmlElement(tag)
    for k, v in attrs.items():
        el.set(qn(k), str(v))
    return el


COMMENTS_REL_TYPE = (
    "http://schemas.openxmlformats.org/officeDocument/2006/relationships/comments"
)
COMMENTS_CONTENT_TYPE = (
    "application/vnd.openxmlformats-officedocument.wordprocessingml.comments+xml"
)


def _ensure_comments_part(doc):
    """Adds /word/comments.xml part if missing. Returns (part, root element)."""
    from docx.opc.part import Part
    from docx.opc.packuri import PackURI

    main_part = doc.part
    package = main_part.package

    # Check existing relationships first
    for rel in main_part.rels.values():
        if rel.reltype == COMMENTS_REL_TYPE:
            comments_part = rel.target_part
            root = etree.fromstring(comments_part.blob)
            return comments_part, root

    partname = PackURI("/word/comments.xml")
    root = etree.Element(qn("w:comments"), nsmap={"w": W_NS})
    blob = etree.tostring(
        root, xml_declaration=True, encoding="UTF-8", standalone=True
    )
    comments_part = Part(partname, COMMENTS_CONTENT_TYPE, blob, package)
    main_part.relate_to(comments_part, COMMENTS_REL_TYPE)
    return comments_part, root


def _sync_comments_part(comments_part, root):
    blob = etree.tostring(
        root, xml_declaration=True, encoding="UTF-8", standalone=True
    )
    comments_part._blob = blob


_comment_counter = {"id": 0}


def add_comment_to_paragraph(doc, paragraph, text, author=AUTHOR):
    """Attaches a Word margin comment to the given paragraph."""
    comments_part, root = _ensure_comments_part(doc)
    cid = _comment_counter["id"]
    _comment_counter["id"] += 1

    # Build comment element
    comment = etree.SubElement(root, qn("w:comment"))
    comment.set(qn("w:id"), str(cid))
    comment.set(qn("w:author"), author)
    comment.set(qn("w:date"), DATE)
    comment.set(qn("w:initials"), "CMD")

    for line in text.split("\n"):
        p = etree.SubElement(comment, qn("w:p"))
        r = etree.SubElement(p, qn("w:r"))
        t = etree.SubElement(r, qn("w:t"))
        t.text = line
        t.set(qn("xml:space"), "preserve")

    _sync_comments_part(comments_part, root)

    # Insert range markers around the paragraph contents
    p_el = paragraph._p
    start = OxmlElement("w:commentRangeStart")
    start.set(qn("w:id"), str(cid))
    end = OxmlElement("w:commentRangeEnd")
    end.set(qn("w:id"), str(cid))
    ref_run = OxmlElement("w:r")
    ref = OxmlElement("w:commentReference")
    ref.set(qn("w:id"), str(cid))
    ref_run.append(ref)

    p_el.insert(0, start)
    p_el.append(end)
    p_el.append(ref_run)


