def _shade_cell(cell, hex_color):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tc_pr.append(shd)


def build_cover(doc, data, L):
    """Cover page: title, score, grade, summary, verdict."""
    title = doc.add_paragraph()
    title_run = title.add_run(L["cover_title"])
    title_run.bold = True
    title_run.font.size = Pt(24)

    sub = doc.add_paragraph()
    sub_run = sub.add_run(data["contract_title"])
    sub_run.italic = True
    sub_run.font.size = Pt(14)
    sub_run.font.color.rgb = RGBColor(0x55, 0x55, 0x55)

    doc.add_paragraph()  # spacer

    # Score table
    score = data.get("score", {})
    table = doc.add_table(rows=2, cols=3)
    table.style = "Light Grid Accent 1"
    hdr = table.rows[0].cells
    hdr[0].text = L["current_score"]
    hdr[1].text = L["after_score"]
    hdr[2].text = L["grade"]
    for c in hdr:
        for p in c.paragraphs:
            for r in p.runs:
                r.bold = True

    body = table.rows[1].cells
    body[0].text = f"{score.get('current','?')}/{score.get('max',100)}"
    body[1].text = f"{score.get('after_redline','?')}/{score.get('max',100)}"
    body[2].text = str(score.get("grade", "?"))
    for p in body[0].paragraphs:
        for r in p.runs:
            r.bold = True
            r.font.size = Pt(20)
            r.font.color.rgb = RGBColor(0xC0, 0x39, 0x2B)
    for p in body[1].paragraphs:
        for r in p.runs:
            r.bold = True
            r.font.size = Pt(20)
            r.font.color.rgb = RGBColor(0x2E, 0x86, 0x36)

    doc.add_paragraph()

    # Severity summary
    summary = data.get("summary", {})
    sev_p = doc.add_paragraph()
    sev_p.add_run(f"🔴 {summary.get('high', 0)} High Risk    ").bold = True
    sev_p.add_run(f"🟡 {summary.get('medium', 0)} Medium    ").bold = True
    sev_p.add_run(f"🟢 {summary.get('low', 0)} Low").bold = True

    if summary.get("verdict"):
        v = doc.add_paragraph()
        v.add_run(f"{L['verdict']}: ").bold = True
        v_run = v.add_run(summary["verdict"])
        v_run.italic = True
        v_run.font.color.rgb = RGBColor(0xC0, 0x39, 0x2B)

    # Instructions
    doc.add_paragraph()
    inst = doc.add_paragraph()
    inst_run = inst.add_run(L["instructions"])
    inst_run.italic = True
    inst_run.font.size = Pt(9)
    inst_run.font.color.rgb = RGBColor(0x77, 0x77, 0x77)

    doc.add_page_break()


def build_change_block(doc, change, L, index):
    """One redlined change: heading + original (tracked deletion) + proposed (tracked insertion) + comment."""
    sev = change.get("severity", "medium")

    h = doc.add_paragraph()
    h.paragraph_format.space_before = Pt(18)
    badge = h.add_run(f"{SEVERITY_LABELS.get(sev,'')}  ")
    badge.bold = True
    badge.font.color.rgb = SEVERITY_COLORS.get(sev)
    badge.font.size = Pt(11)

    sec_run = h.add_run(f"{L['section']} {change.get('section','?')} — {change.get('title','')}")
    sec_run.bold = True
    sec_run.font.size = Pt(13)

    # Original (deleted)
    orig_p = doc.add_paragraph()
    orig_label = orig_p.add_run(f"{L['original']}: ")
    orig_label.bold = True
    orig_label.font.size = Pt(9)
    orig_label.font.color.rgb = RGBColor(0x77, 0x77, 0x77)
    add_tracked_deletion(orig_p, change.get("original", ""))

    # Proposed (inserted)
    new_p = doc.add_paragraph()
    new_label = new_p.add_run(f"{L['proposed']}: ")
    new_label.bold = True
    new_label.font.size = Pt(9)
    new_label.font.color.rgb = RGBColor(0x77, 0x77, 0x77)
    add_tracked_insertion(new_p, change.get("proposed", ""))

    # Build comment text
    comment_lines = []
    if change.get("why"):
        comment_lines.append(f"{L['why']}: {change['why']}")
    if change.get("legal_basis"):
        comment_lines.append(f"{L['legal']}: {change['legal_basis']}")
    if change.get("risk"):
        comment_lines.append(f"{L['risk']}: {change['risk']}")
    if change.get("protects"):
        comment_lines.append(f"{L['protects']}: {change['protects']}")
    if change.get("tip"):
        comment_lines.append(f"{L['tip']}: {change['tip']}")

    if comment_lines:
        # Anchor comment on the new_p paragraph (the proposed text)
        add_comment_to_paragraph(doc, new_p, "\n\n".join(comment_lines))

    # Visual inline explanation card (so it's readable even with revisions hidden)
    card = doc.add_table(rows=len(comment_lines), cols=1)
    card.autofit = True
    for i, line in enumerate(comment_lines):
        cell = card.rows[i].cells[0]
        _shade_cell(cell, "FFF8DC")  # soft yellow
        cell.text = line
        for p in cell.paragraphs:
            for r in p.runs:
                r.font.size = Pt(9)


def build_overview_table(doc, data, L):
    doc.add_page_break()
    h = doc.add_paragraph()
    h_run = h.add_run(L["overview"])
    h_run.bold = True
    h_run.font.size = Pt(16)

    changes = data.get("changes", [])
    table = doc.add_table(rows=len(changes) + 1, cols=4)
    table.style = "Light List Accent 1"

    hdr = table.rows[0].cells
    hdr[0].text = L["section"]
    hdr[1].text = "Severity"
    hdr[2].text = "Title"
    hdr[3].text = L["risk"]
    for c in hdr:
        for p in c.paragraphs:
            for r in p.runs:
                r.bold = True

    for i, ch in enumerate(changes, start=1):
        row = table.rows[i].cells
        row[0].text = str(ch.get("section", ""))
        sev = ch.get("severity", "medium")
        row[1].text = SEVERITY_LABELS.get(sev, "")
        row[2].text = str(ch.get("title", ""))
        row[3].text = str(ch.get("risk", "") or "")
        for c in row:
            for p in c.paragraphs:
                for r in p.runs:
                    r.font.size = Pt(9)


def add_footer(doc, L):
    section = doc.sections[0]
    footer = section.footer
    p = footer.paragraphs[0]
    p.text = f"{L['footer']}{datetime.utcnow().strftime('%Y-%m-%d')}"
    for r in p.runs:
        r.font.size = Pt(8)
        r.font.color.rgb = RGBColor(0x99, 0x99, 0x99)


